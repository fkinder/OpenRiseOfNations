// Writes apps/map-mac/keymap_table.inc: the gameplay rows of the default hotkey table (`node re/tools/keymap.mjs`) as C
// initialisers {entry name, key string, mode, selection context, option, param}. Debug (SYSTEM_*), script IDE (MENU_*) and
// unbound entries are left out. ronmap compiles the table in; the install's exe is not read at run time.
//   node re/tools/keymap-inc.mjs > apps/map-mac/keymap_table.inc
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const text = execFileSync('node', [path.join(here, 'keymap.mjs')], { encoding: 'utf8', maxBuffer: 1 << 26 });
const modes = { STANDARD_OPTIONS: 0, BUILD_OPTIONS: 1, SCRIPT_IDE_OPTIONS: 4 };
const out = ['// Generated by re/tools/keymap-inc.mjs from the default KeyMap table (ui-spec 4.2). name, keys, mode (0 standard, 1 build menu),',
	'// selection context (-1 always, -2/-4 buildings, -3 units, -5 aircraft, -6 land/sea units, >= 0 a TypeIndex selected), option, param.'];
for (const line of text.split('\n')) {
	const m = line.match(/^\s*(\d+)\s+(\S+)\s+(.+?)\s+(STANDARD_OPTIONS|BUILD_OPTIONS|SCRIPT_IDE_OPTIONS)\s+type=(-?\d+)\s+g\S+\s+(\S+)/);
	if (!m) continue;
	const [, , name, keys, mode, type, opt] = m;
	if (/^(SYSTEM_|MENU_|TERRAINDEBUG)/.test(name) || mode === 'SCRIPT_IDE_OPTIONS') continue;
	let option = opt, param = -1;
	if (opt === '-') option = name;
	const sl = option.indexOf('/');
	if (sl > 0) { param = parseInt(option.slice(sl + 1), 10); option = option.slice(0, sl); }
	if (!/^[A-Z_0-9]+$/.test(option)) continue;
	const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
	out.push(`{"${name}", "${esc(keys.trim())}", ${modes[mode]}, ${type}, "${option}", ${param}},`);
}
process.stdout.write(out.join('\n') + '\n');
